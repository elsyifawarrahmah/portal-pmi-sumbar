create table if not exists pmi_organisasi (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  urut integer not null,
  jenis text not null check (jenis in ('provinsi','kota','kabupaten')),
  nama text not null,
  region_id text,                 -- id wilayah di peta infografis
  ketua text,
  masa_bakti text,                -- mis. "2026 - 2031"
  tgl_sk text,                    -- ditulis apa adanya, mis. "23 Juni"
  keterangan text,                -- mis. MUSKAB, Pengajuan
  kode_wilayah text,              -- mis. 01.04.01
  markas_alamat text,
  markas_telp text,
  markas_email text,              -- boleh lebih dari satu, satu baris satu e-mail
  catatan_pengurus text,          -- mis. Pergantian Antar Waktu
  updated_at timestamptz default now(),
  updated_by uuid references profiles(id)
);

create table if not exists pmi_pengurus (
  id uuid primary key default gen_random_uuid(),
  organisasi_id uuid not null references pmi_organisasi(id) on delete cascade,
  kelompok text not null check (kelompok in ('Pelindung','Dewan Kehormatan','Pengurus')),
  jabatan text not null,
  nama text not null,
  urut integer not null default 0,
  created_at timestamptz default now()
);
create index if not exists pmi_pengurus_org_idx on pmi_pengurus (organisasi_id, urut);

create table if not exists pmi_unit (
  id uuid primary key default gen_random_uuid(),
  organisasi_id uuid not null references pmi_organisasi(id) on delete cascade,
  jenis text not null check (jenis in ('pusdiklat','klinik')),
  nama text not null,
  alamat text,
  telp text,
  email text,
  penanggung_jawab text,
  keterangan text,
  created_at timestamptz default now()
);

create table if not exists relawan (
  id uuid primary key default gen_random_uuid(),
  organisasi_id uuid not null unique references pmi_organisasi(id) on delete cascade,
  ksr integer not null default 0,
  tsr integer not null default 0,
  dds integer not null default 0,
  pmr_mula integer not null default 0,
  pmr_madya integer not null default 0,
  pmr_wira integer not null default 0,
  diperbarui date,
  updated_by uuid references profiles(id)
);

-- Keamanan baris: semua yang login bisa melihat, hanya admin yang menambah/mengubah/menghapus
do $$
declare t text;
begin
  foreach t in array array['pmi_organisasi','pmi_pengurus','pmi_unit','relawan'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "Login bisa lihat %1$s" on %1$I', t);
    execute format('drop policy if exists "Admin bisa tambah %1$s" on %1$I', t);
    execute format('drop policy if exists "Admin bisa ubah %1$s" on %1$I', t);
    execute format('drop policy if exists "Admin bisa hapus %1$s" on %1$I', t);
    execute format('create policy "Login bisa lihat %1$s" on %1$I for select using (auth.role() = ''authenticated'')', t);
    execute format('create policy "Admin bisa tambah %1$s" on %1$I for insert with check (exists (select 1 from profiles where id = auth.uid() and role = ''admin''))', t);
    execute format('create policy "Admin bisa ubah %1$s" on %1$I for update using (exists (select 1 from profiles where id = auth.uid() and role = ''admin''))', t);
    execute format('create policy "Admin bisa hapus %1$s" on %1$I for delete using (exists (select 1 from profiles where id = auth.uid() and role = ''admin''))', t);
  end loop;
end $$;

